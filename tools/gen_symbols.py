#!/usr/bin/env python3
"""Generate the library names: symbol_addrs.<module>.<version>.txt and
lib_objects.<version>.txt.

tools/libmatch.py finds libultra in the code image (docs/LIBULTRA.md).  This
writes what it finds for splat:

  * symbol_addrs.<module>.<version>.txt, for boot_code and main_code: below
    a marker line, every libultra name with how it was found: `lib=exact`
    (the body matches a reference object), `lib=fuzzy` (it differs by a few
    instructions), `lib=ref` (a matched function calls or references it by
    that name).  Lines above the marker are kept, for names given by hand.
    tools/layout.py lists every such file in the splat config.
  * lib_objects.<version>.txt: where matched library objects start and end
    in each module's text.  tools/layout.py splits the text there as well as
    where IDO's padding shows a boundary (a function that ends on a 16-byte
    boundary leaves none).

Only library code is named; everything else keeps splat's address names.
The overlays are left out: two of them carry their own osSpTaskYield and
__osSpSetStatus, but every overlay links at 0x80043000 into one image, so a
plain name there would clash (their names carry the bank and entry, which
is for the game's own code to settle first).

Adapted from Blast Corps' tools/gen_symbols.py (../BlastCorps).

Usage:
  gen_symbols.py <version> <objdir> [<objdir> ...]   # see tools/build_ultralib.sh
"""
import argparse
from pathlib import Path

import libmatch

ROOT = libmatch.ROOT
MARKER = "// ---- generated by tools/gen_symbols.py below this line; edits there are lost ----"
MODULES = ("boot_code", "main_code")
BOOT_VRAM = 0x80000400  # boot_code's start; below it is low RDRAM


def tag(ev):
    if any(e.startswith("fuzzy") for e in ev):
        return "lib=fuzzy"
    return "lib=exact" if any("match" in e for e in ev) else "lib=ref"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("version")
    ap.add_argument("objdirs", nargs="+", type=Path)
    args = ap.parse_args()
    ver = args.version

    lib, bounds, _ = libmatch.match_version(ver, args.objdirs)
    segs = {name: (start, end, vram) for name, start, end, vram in libmatch.code_segments(ver)}

    def in_text(addr):
        return any(vram <= addr < vram + end - start for start, end, vram in segs.values())

    objects = [f"# Generated by tools/gen_symbols.py from libultra's objects; don't edit by hand.",
               "# module, VRAM, and where a matched library object starts or ends there"]
    for m in MODULES:
        path = ROOT / f"symbol_addrs.{m}.{ver}.txt"
        manual = []
        if path.exists():
            text = path.read_text().splitlines()
            manual = text[:text.index(MARKER)] if MARKER in text else text
        taken = [l.split("=")[0].strip() for l in manual if "=" in l and not l.lstrip().startswith("//")]
        out = manual + [MARKER]
        for addr, name, kind, ev in lib[m]:
            if name in taken:
                continue
            # a label in code that libultra's asm takes the address of
            # (__osException) is a function all the same
            if kind == "data" and in_text(addr):
                kind = "func"
            # splat knows no `type:data`; data keeps whatever type it infers.
            # Each code segment has a RAM id, so a name says which one it is
            # in.  libultra's globals in low RDRAM (osTvType, ...: the boot
            # parameters at 0x80000300) are in no segment: absolute, and
            # tools/ld_fix.py defines them for the link.
            attrs = ["type:func"] if kind == "func" else []
            attrs.append("absolute:True" if addr < BOOT_VRAM else f"segment:{m}")
            out.append(f"{name} = 0x{addr:08X}; // {' '.join(attrs)} {tag(ev)}")
        path.write_text("\n".join(out) + "\n")
        print(f"{path.name}: {len(lib[m])} names")
        start, end, vram = segs[m]
        for addr, what in sorted(bounds[m].items()):
            if vram <= addr < vram + end - start:
                objects.append(f"{m} 0x{addr:08X} {what}")
    path = ROOT / f"lib_objects.{ver}.txt"
    path.write_text("\n".join(objects) + "\n")
    print(f"{path.name}: {len(objects) - 2} object bounds")


if __name__ == "__main__":
    main()
